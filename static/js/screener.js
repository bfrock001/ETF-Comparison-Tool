(function () {
  "use strict";

  const els = {
    tabs: document.querySelectorAll(".tab[data-tab]"),
    panels: {
      compare: document.getElementById("panel-compare"),
      screener: document.getElementById("panel-screener"),
    },
    select: document.getElementById("asset-class-select"),
    typePills: document.querySelectorAll(".type-filter .pill[data-type]"),
    asof: document.getElementById("screener-asof"),
    error: document.getElementById("screener-error"),
    title: document.getElementById("screener-title"),
    table: document.getElementById("screener-table"),
    tbody: document.querySelector("#screener-table tbody"),
    headers: document.querySelectorAll("#screener-table th.sortable"),
  };

  // Columns where a lower number is better, so the first click sorts ascending.
  const LOWER_IS_BETTER = new Set(["expense"]);
  // Columns that sort as text.
  const TEXT_COLS = new Set(["name"]);

  let dataset = null;          // full JSON payload
  let classIndex = {};         // id -> class object
  let currentClass = null;     // class object
  let typeFilter = "all";
  let sortKey = "aum";
  let sortDir = "desc";
  let loaded = false;

  // ---- tab switching ------------------------------------------------------
  function activateTab(name) {
    els.tabs.forEach((t) => {
      const on = t.dataset.tab === name;
      t.classList.toggle("active", on);
      t.setAttribute("aria-selected", on ? "true" : "false");
    });
    Object.entries(els.panels).forEach(([key, panel]) => {
      if (panel) panel.classList.toggle("hidden", key !== name);
    });
    if (name === "screener" && !loaded) loadData();
  }

  // ---- data ---------------------------------------------------------------
  async function loadData() {
    loaded = true;
    els.asof.textContent = "Loading fund data…";
    try {
      const res = await fetch("/api/screener", { cache: "no-store" });
      if (!res.ok) throw new Error("HTTP " + res.status);
      dataset = await res.json();
    } catch (e) {
      loaded = false;
      showError(
        "Fund tables aren't available yet. They're generated by a build step " +
        "(build_universe.py) and served as static data."
      );
      els.asof.textContent = "";
      return;
    }
    showError(null);
    classIndex = {};
    dataset.classes.forEach((c) => { classIndex[c.id] = c; });
    populateSelect(dataset.classes);
    if (dataset.generated) {
      const d = new Date(dataset.generated);
      els.asof.textContent = "Data as of " + d.toLocaleDateString(undefined, {
        year: "numeric", month: "long", day: "numeric",
      }) + " · dividend-adjusted, via Yahoo Finance.";
    }
    const first = dataset.classes[0];
    if (first) { els.select.value = first.id; selectClass(first.id); }
  }

  function populateSelect(classes) {
    els.select.innerHTML = "";
    const groups = {};
    const order = [];
    classes.forEach((c) => {
      if (!groups[c.group]) { groups[c.group] = []; order.push(c.group); }
      groups[c.group].push(c);
    });
    order.forEach((g) => {
      const og = document.createElement("optgroup");
      og.label = g;
      groups[g].forEach((c) => {
        const opt = document.createElement("option");
        opt.value = c.id;
        opt.textContent = c.label;
        og.appendChild(opt);
      });
      els.select.appendChild(og);
    });
  }

  function selectClass(id) {
    currentClass = classIndex[id];
    if (!currentClass) return;
    els.title.textContent = currentClass.label + " — largest funds";
    render();
  }

  // ---- rendering ----------------------------------------------------------
  function visibleRows() {
    let rows = currentClass.funds.slice();
    if (typeFilter !== "all") {
      rows = rows.filter((r) => matchesType(r, typeFilter));
    }
    rows.sort(compareRows);
    return rows;
  }

  function matchesType(row, filter) {
    if (filter === "Mutual Fund") {
      // Money-market funds are a kind of mutual fund; group them here.
      return row.type === "Mutual Fund" || row.type === "Money Market";
    }
    return row.type === filter;
  }

  function compareRows(a, b) {
    const av = a[sortKey];
    const bv = b[sortKey];
    const an = av === null || av === undefined;
    const bn = bv === null || bv === undefined;
    if (an && bn) return 0;
    if (an) return 1;   // nulls always sink to the bottom
    if (bn) return -1;
    let cmp;
    if (TEXT_COLS.has(sortKey)) cmp = String(av).localeCompare(String(bv));
    else cmp = av - bv;
    return sortDir === "asc" ? cmp : -cmp;
  }

  function fmtPct(v) {
    if (v === null || v === undefined || Number.isNaN(v)) return "—";
    const cls = v >= 0 ? "pos" : "neg";
    return '<span class="' + cls + '">' + (v >= 0 ? "+" : "") + v.toFixed(2) + "%</span>";
  }

  function fmtExpense(v) {
    if (v === null || v === undefined || Number.isNaN(v)) return "—";
    if (v === 0) return "0.00%";
    // Sub-0.1% fees get 3 decimals so 0.015% doesn't collapse to 0.01%.
    let s = v < 0.1 ? v.toFixed(3) : v.toFixed(2);
    if (s.indexOf(".") >= 0) s = s.replace(/0+$/, "").replace(/\.$/, "");
    return s + "%";
  }

  function fmtSharpe(v) {
    if (v === null || v === undefined || Number.isNaN(v)) return "—";
    return v.toFixed(2);
  }

  function fmtAum(v) {
    if (!v || Number.isNaN(v)) return "—";
    if (v >= 1e12) return "$" + (v / 1e12).toFixed(2) + "T";
    if (v >= 1e9) return "$" + (v / 1e9).toFixed(1) + "B";
    if (v >= 1e6) return "$" + (v / 1e6).toFixed(0) + "M";
    return "$" + v.toLocaleString();
  }

  function typeChip(type) {
    const short = type === "Mutual Fund" ? "MF" : type === "Money Market" ? "MMF" : "ETF";
    const cls = short.toLowerCase();
    return '<span class="type-chip type-chip--' + cls + '" title="' + type + '">' + short + "</span>";
  }

  function render() {
    els.tbody.innerHTML = "";
    const rows = visibleRows();
    if (!rows.length) {
      els.tbody.innerHTML =
        '<tr><td colspan="10" class="empty-row">No ' +
        (typeFilter === "all" ? "" : typeFilter.toLowerCase() + " ") +
        "funds in this class.</td></tr>";
      updateHeaderIndicators();
      return;
    }
    rows.forEach((r) => {
      const isAnchor = r.ticker === currentClass.anchor;
      const tr = document.createElement("tr");
      if (isAnchor) tr.className = "anchor-row";
      const nameCell =
        "<div class='fund-name'>" +
          typeChip(r.type) +
          "<span class='fund-name__text'>" + (r.name || r.ticker) + "</span>" +
          (isAnchor ? " <span class='anchor-tag'>★ pick</span>" : "") +
        "</div>" +
        "<div class='fund-sub'>" + r.ticker +
          (r.note ? " · <span class='fund-note' title=\"" + r.note.replace(/"/g, "&quot;") + "\">yield-based ⓘ</span>" : "") +
        "</div>";
      tr.innerHTML =
        "<td>" + nameCell + "</td>" +
        "<td class='num'>" + fmtAum(r.aum) + "</td>" +
        "<td class='num'>" + fmtExpense(r.expense) + "</td>" +
        "<td class='num'>" + fmtPct(r.ytd) + "</td>" +
        "<td class='num'>" + fmtPct(r.r1y) + "</td>" +
        "<td class='num'>" + fmtPct(r.r3y) + "</td>" +
        "<td class='num'>" + fmtPct(r.r5y) + "</td>" +
        "<td class='num'>" + fmtPct(r.r10y) + "</td>" +
        "<td class='num'>" + fmtPct(r.life) + "</td>" +
        "<td class='num'>" + fmtSharpe(r.sharpe) + "</td>";
      els.tbody.appendChild(tr);
    });
    updateHeaderIndicators();
  }

  function updateHeaderIndicators() {
    els.headers.forEach((th) => {
      th.classList.remove("sorted-asc", "sorted-desc");
      if (th.dataset.sort === sortKey) {
        th.classList.add(sortDir === "asc" ? "sorted-asc" : "sorted-desc");
      }
    });
  }

  // ---- error --------------------------------------------------------------
  function showError(msg) {
    if (!msg) { els.error.classList.add("hidden"); return; }
    els.error.textContent = msg;
    els.error.classList.remove("hidden");
  }

  // ---- wiring -------------------------------------------------------------
  function wire() {
    els.tabs.forEach((t) => t.addEventListener("click", () => activateTab(t.dataset.tab)));

    els.select.addEventListener("change", () => selectClass(els.select.value));

    els.typePills.forEach((p) => p.addEventListener("click", () => {
      els.typePills.forEach((x) => x.classList.remove("active"));
      p.classList.add("active");
      typeFilter = p.dataset.type;
      if (currentClass) render();
    }));

    els.headers.forEach((th) => th.addEventListener("click", () => {
      const key = th.dataset.sort;
      if (sortKey === key) {
        sortDir = sortDir === "asc" ? "desc" : "asc";
      } else {
        sortKey = key;
        sortDir = LOWER_IS_BETTER.has(key) || TEXT_COLS.has(key) ? "asc" : "desc";
      }
      if (currentClass) render();
    }));
  }

  document.addEventListener("DOMContentLoaded", wire);
})();
