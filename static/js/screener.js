(function () {
  "use strict";

  const els = {
    tabs: document.querySelectorAll(".tab[data-tab]"),
    panels: {
      compare: document.getElementById("panel-compare"),
      screener: document.getElementById("panel-screener"),
    },
    select: document.getElementById("asset-class-select"),
    typePills: document.querySelectorAll(".type-filter .pill[data-type]"),
    asof: document.getElementById("screener-asof"),
    error: document.getElementById("screener-error"),
    title: document.getElementById("screener-title"),
    table: document.getElementById("screener-table"),
    tbody: document.querySelector("#screener-table tbody"),
    headers: document.querySelectorAll("#screener-table th.sortable"),
    selection: document.getElementById("finder-selection"),
    showSelect: document.getElementById("show-count-select"),
    count: document.getElementById("screener-count"),
    modal: document.getElementById("fund-modal"),
    modalBody: document.getElementById("fund-modal-body"),
  };

  // Columns where a lower number is better, so the first click sorts ascending.
  const LOWER_IS_BETTER = new Set(["expense"]);
  // Columns that sort as text.
  const TEXT_COLS = new Set(["name"]);
  const MAX_SELECT = 5;

  const selected = new Set();  // tickers chosen for comparison (persists across classes)

  let dataset = null;          // full JSON payload
  let classIndex = {};         // id -> class object
  let fundByTicker = {};       // ticker -> row (for the detail modal's returns strip)
  let currentClass = null;     // class object
  let typeFilter = "all";
  let sortKey = "aum";
  let sortDir = "desc";
  let showCount = 10;          // 10 | 25 | Infinity ("all")
  let loaded = false;

  // ---- tab switching ------------------------------------------------------
  function activateTab(name) {
    els.tabs.forEach((t) => {
      const on = t.dataset.tab === name;
      t.classList.toggle("active", on);
      t.setAttribute("aria-selected", on ? "true" : "false");
    });
    Object.entries(els.panels).forEach(([key, panel]) => {
      if (panel) panel.classList.toggle("hidden", key !== name);
    });
    if (name === "screener" && !loaded) loadData();
  }

  // ---- data ---------------------------------------------------------------
  async function loadData() {
    loaded = true;
    els.asof.textContent = "Loading fund data…";
    try {
      const res = await fetch("/api/screener", { cache: "no-store" });
      if (!res.ok) throw new Error("HTTP " + res.status);
      dataset = await res.json();
    } catch (e) {
      loaded = false;
      showError(
        "Fund tables aren't available yet. They're generated by a build step " +
        "(build_universe.py) and served as static data."
      );
      els.asof.textContent = "";
      return;
    }
    showError(null);
    classIndex = {};
    fundByTicker = {};
    dataset.classes.forEach((c) => {
      classIndex[c.id] = c;
      c.funds.forEach((f) => { if (!fundByTicker[f.ticker]) fundByTicker[f.ticker] = f; });
    });
    populateSelect(dataset.classes);
    if (dataset.generated) {
      const d = new Date(dataset.generated);
      els.asof.textContent = "Data as of " + d.toLocaleDateString(undefined, {
        year: "numeric", month: "long", day: "numeric",
      }) + " · dividend-adjusted, via Yahoo Finance.";
    }
    // Force the display controls to their defaults so a browser-restored
    // value can't leave the control out of sync with the rendered rows.
    els.showSelect.value = "10";
    showCount = 10;
    const first = dataset.classes[0];
    if (first) { els.select.value = first.id; selectClass(first.id); }
  }

  function populateSelect(classes) {
    els.select.innerHTML = "";
    const groups = {};
    const order = [];
    classes.forEach((c) => {
      if (!groups[c.group]) { groups[c.group] = []; order.push(c.group); }
      groups[c.group].push(c);
    });
    order.forEach((g) => {
      const og = document.createElement("optgroup");
      og.label = g;
      groups[g].forEach((c) => {
        const opt = document.createElement("option");
        opt.value = c.id;
        opt.textContent = c.label;
        og.appendChild(opt);
      });
      els.select.appendChild(og);
    });
  }

  function selectClass(id) {
    currentClass = classIndex[id];
    if (!currentClass) return;
    els.title.textContent = currentClass.label + " — largest funds";
    render();
  }

  // ---- rendering ----------------------------------------------------------
  function visibleRows() {
    let rows = currentClass.funds.slice();
    if (typeFilter !== "all") {
      rows = rows.filter((r) => matchesType(r, typeFilter));
    }
    rows.sort(compareRows);
    return rows;
  }

  function matchesType(row, filter) {
    if (filter === "Mutual Fund") {
      // Money-market funds are a kind of mutual fund; group them here.
      return row.type === "Mutual Fund" || row.type === "Money Market";
    }
    return row.type === filter;
  }

  function compareRows(a, b) {
    const av = a[sortKey];
    const bv = b[sortKey];
    const an = av === null || av === undefined;
    const bn = bv === null || bv === undefined;
    if (an && bn) return 0;
    if (an) return 1;   // nulls always sink to the bottom
    if (bn) return -1;
    let cmp;
    if (TEXT_COLS.has(sortKey)) cmp = String(av).localeCompare(String(bv));
    else cmp = av - bv;
    return sortDir === "asc" ? cmp : -cmp;
  }

  function fmtPct(v) {
    if (v === null || v === undefined || Number.isNaN(v)) return "—";
    const cls = v >= 0 ? "pos" : "neg";
    return '<span class="' + cls + '">' + (v >= 0 ? "+" : "") + v.toFixed(2) + "%</span>";
  }

  function fmtExpense(v) {
    if (v === null || v === undefined || Number.isNaN(v)) return "—";
    if (v === 0) return "0.00%";
    // Sub-0.1% fees get 3 decimals so 0.015% doesn't collapse to 0.01%.
    let s = v < 0.1 ? v.toFixed(3) : v.toFixed(2);
    if (s.indexOf(".") >= 0) s = s.replace(/0+$/, "").replace(/\.$/, "");
    return s + "%";
  }

  function fmtSharpe(v) {
    if (v === null || v === undefined || Number.isNaN(v)) return "—";
    return v.toFixed(2);
  }

  function fmtAum(v) {
    if (!v || Number.isNaN(v)) return "—";
    if (v >= 1e12) return "$" + (v / 1e12).toFixed(2) + "T";
    if (v >= 1e9) return "$" + (v / 1e9).toFixed(1) + "B";
    if (v >= 1e6) return "$" + (v / 1e6).toFixed(0) + "M";
    return "$" + v.toLocaleString();
  }

  function typeChip(type) {
    const short = type === "Mutual Fund" ? "MF" : type === "Money Market" ? "MMF" : "ETF";
    const cls = short.toLowerCase();
    return '<span class="type-chip type-chip--' + cls + '" title="' + type + '">' + short + "</span>";
  }

  function render() {
    els.tbody.innerHTML = "";
    const all = visibleRows();                    // filtered + sorted
    const rows = showCount === Infinity ? all : all.slice(0, showCount);
    if (!all.length) {
      els.tbody.innerHTML =
        '<tr><td colspan="11" class="empty-row">No ' +
        (typeFilter === "all" ? "" : typeFilter.toLowerCase() + " ") +
        "funds in this class.</td></tr>";
      updateCount(0, 0);
      updateHeaderIndicators();
      return;
    }
    rows.forEach((r) => {
      const tr = document.createElement("tr");
      const nameCell =
        "<div class='fund-name'>" +
          typeChip(r.type) +
          "<button type='button' class='fund-link' data-ticker='" + r.ticker + "'>" +
            (r.name || r.ticker) + "</button>" +
        "</div>" +
        "<div class='fund-sub'>" + r.ticker +
          (r.note ? " · <span class='fund-note' title=\"" + r.note.replace(/"/g, "&quot;") + "\">yield-based ⓘ</span>" : "") +
        "</div>";
      tr.innerHTML =
        "<td class='select-cell'><input type='checkbox' class='fund-check' data-ticker='" +
          r.ticker + "' aria-label='Select " + r.ticker + "'></td>" +
        "<td>" + nameCell + "</td>" +
        "<td class='num'>" + fmtAum(r.aum) + "</td>" +
        "<td class='num'>" + fmtExpense(r.expense) + "</td>" +
        "<td class='num'>" + fmtPct(r.ytd) + "</td>" +
        "<td class='num'>" + fmtPct(r.r1y) + "</td>" +
        "<td class='num'>" + fmtPct(r.r3y) + "</td>" +
        "<td class='num'>" + fmtPct(r.r5y) + "</td>" +
        "<td class='num'>" + fmtPct(r.r10y) + "</td>" +
        "<td class='num'>" + fmtPct(r.life) + "</td>" +
        "<td class='num'>" + fmtSharpe(r.sharpe) + "</td>";
      els.tbody.appendChild(tr);
    });
    updateHeaderIndicators();
    refreshChecks();
    updateCount(rows.length, all.length);
  }

  function updateCount(shown, total) {
    if (!total) { els.count.textContent = ""; return; }
    els.count.textContent = shown < total
      ? "Showing the top " + shown + " of " + total + " funds (ranked by the sorted column)."
      : "Showing all " + total + " funds in this class.";
  }

  function updateHeaderIndicators() {
    els.headers.forEach((th) => {
      th.classList.remove("sorted-asc", "sorted-desc");
      if (th.dataset.sort === sortKey) {
        th.classList.add(sortDir === "asc" ? "sorted-asc" : "sorted-desc");
      }
    });
  }

  // ---- selection ----------------------------------------------------------
  // Sync the visible checkboxes to the selection set and disable the rest once
  // five are chosen. The set itself persists across class / filter / sort.
  function refreshChecks() {
    const full = selected.size >= MAX_SELECT;
    els.tbody.querySelectorAll(".fund-check").forEach((cb) => {
      cb.checked = selected.has(cb.dataset.ticker);
      cb.disabled = full && !cb.checked;
    });
  }

  function renderSelectionBar() {
    const n = selected.size;
    if (!n) {
      els.selection.classList.add("hidden");
      els.selection.innerHTML = "";
      return;
    }
    const chips = [...selected].map((t) =>
      "<span class='sel-chip'>" + t +
      "<button type='button' class='sel-chip__x' data-remove='" + t +
      "' aria-label='Remove " + t + "'>×</button></span>"
    ).join("");
    els.selection.innerHTML =
      "<span class='finder-selection__label'>Compare</span>" +
      "<span class='sel-chips'>" + chips + "</span>" +
      "<span class='finder-selection__count'>" + n + " / " + MAX_SELECT + "</span>" +
      "<button type='button' id='compare-selected' class='primary-btn primary-btn--sm'>" +
        "Compare selected →</button>" +
      "<button type='button' id='clear-selection' class='link-btn'>Clear</button>";
    els.selection.classList.remove("hidden");
  }

  function selectionChanged() {
    renderSelectionBar();
    refreshChecks();
  }

  function clearSelection() {
    selected.clear();
    selectionChanged();
  }

  function compareSelected() {
    if (!selected.size || !window.ETFCompare) return;
    window.ETFCompare.setTickers([...selected]);
    activateTab("compare");
    window.ETFCompare.run();
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  // ---- fund detail modal --------------------------------------------------
  function fmtMoney(v, cur) {
    if (v === null || v === undefined || Number.isNaN(v)) return "—";
    const sym = cur === "USD" || !cur ? "$" : "";
    return sym + v.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }

  function fmtMktCap(m) {  // m is in $millions
    if (m === null || m === undefined || Number.isNaN(m) || m === 0) return "—";
    if (m >= 1e6) return "$" + (m / 1e6).toFixed(2) + "T";
    if (m >= 1e3) return "$" + (m / 1e3).toFixed(1) + "B";
    return "$" + m.toFixed(0) + "M";
  }

  function bars(items, max, unit) {
    return "<ul class='fm-bars'>" + items.map((it) =>
      "<li><span class='fm-bar__label'>" + it.name + "</span>" +
      "<span class='fm-bar__track'><span class='fm-bar__fill' style='width:" +
        (max > 0 ? Math.max(2, (it.pct / max) * 100) : 0) + "%'></span></span>" +
      "<span class='fm-bar__val'>" + it.pct.toFixed(2) + unit + "</span></li>"
    ).join("") + "</ul>";
  }

  function statTile(label, value) {
    return "<div class='fm-stat'><div class='fm-stat__label'>" + label +
      "</div><div class='fm-stat__val'>" + value + "</div></div>";
  }

  function openFundDetail(ticker) {
    ticker = String(ticker).toUpperCase();
    els.modal.classList.remove("hidden");
    document.body.classList.add("modal-open");
    els.modalBody.innerHTML = "<div class='fm-loading'><span class='spinner'></span>Loading " +
      ticker + " …</div>";
    fetch("/api/fund/" + encodeURIComponent(ticker))
      .then((res) => res.json().then((d) => ({ ok: res.ok, d })))
      .then(({ ok, d }) => {
        if (!ok) throw new Error(d && d.error ? d.error : "Failed to load.");
        renderFundDetail(d);
      })
      .catch((e) => {
        els.modalBody.innerHTML = "<div class='fm-error'>Couldn't load details for " +
          ticker + ".<br><span class='muted'>" + (e.message || "") + "</span></div>";
      });
  }

  function renderFundDetail(d) {
    const row = fundByTicker[d.ticker];
    const chgCls = (d.change_pct || 0) >= 0 ? "pos" : "neg";
    const chg = d.change_pct === null || d.change_pct === undefined ? "" :
      "<div class='fm-price__chg " + chgCls + "'>" +
      (d.change >= 0 ? "+" : "") + (d.change != null ? d.change.toFixed(2) : "") +
      " (" + (d.change_pct >= 0 ? "+" : "") + d.change_pct.toFixed(2) + "%)</div>";

    let facts =
      statTile("Type", d.type) +
      statTile("Expense", fmtExpense(d.expense)) +
      statTile("AUM", fmtAum(d.aum)) +
      statTile("Yield", d.yield != null ? d.yield.toFixed(2) + "%" : "—");
    if (row) {
      facts += statTile("YTD", fmtPct(row.ytd)) + statTile("1Y", fmtPct(row.r1y)) +
        statTile("3Y", fmtPct(row.r3y)) + statTile("5Y", fmtPct(row.r5y)) +
        statTile("10Y", fmtPct(row.r10y)) + statTile("Life", fmtPct(row.life)) +
        statTile("Sharpe", fmtSharpe(row.sharpe));
    }

    const sections = [];

    if (d.holdings && d.holdings.length) {
      sections.push(
        "<section class='fm-sec'><h3>Top 10 Holdings</h3>" +
        "<table class='fm-holdings'><tbody>" +
        d.holdings.map((h) =>
          "<tr><td class='fm-sym'>" + h.symbol + "</td><td class='fm-hname'>" +
          (h.name || "") + "</td><td class='num'>" +
          (h.pct != null ? h.pct.toFixed(2) + "%" : "—") + "</td></tr>"
        ).join("") + "</tbody></table></section>"
      );
    }
    if (d.sectors && d.sectors.length) {
      const max = Math.max.apply(null, d.sectors.map((s) => s.pct));
      sections.push("<section class='fm-sec'><h3>Sector Weightings</h3>" + bars(d.sectors, max, "%") + "</section>");
    }

    const grid1 = sections.length
      ? "<div class='fm-grid'>" + sections.join("") + "</div>" : "";

    const sections2 = [];
    const comp = d.composition || {};
    if (comp.stock != null) {
      const items = [
        { name: "Stocks", pct: comp.stock }, { name: "Bonds", pct: comp.bond },
        { name: "Cash", pct: comp.cash }, { name: "Other", pct: comp.other },
      ].filter((x) => x.pct && x.pct > 0);
      if (items.length) {
        sections2.push("<section class='fm-sec'><h3>Portfolio Composition</h3>" + bars(items, 100, "%") + "</section>");
      }
    }
    if (d.bond_ratings && d.bond_ratings.length) {
      const max = Math.max.apply(null, d.bond_ratings.map((r) => r.pct));
      sections2.push("<section class='fm-sec'><h3>Bond Credit Quality</h3>" + bars(d.bond_ratings, max, "%") + "</section>");
    }
    const grid2 = sections2.length
      ? "<div class='fm-grid'>" + sections2.join("") + "</div>" : "";

    let equity = "";
    const eq = d.equity || {};
    if (eq.pe != null || eq.pb != null || eq.median_mktcap != null) {
      const cat = eq.cat || {};
      const showCat = cat.pe != null || cat.pb != null || cat.ps != null || cat.pcf != null;
      const rowsE = [
        ["Price / Earnings", eq.pe, cat.pe], ["Price / Book", eq.pb, cat.pb],
        ["Price / Sales", eq.ps, cat.ps], ["Price / Cashflow", eq.pcf, cat.pcf],
        ["Median Market Cap", eq.median_mktcap != null ? fmtMktCap(eq.median_mktcap) : "—", null, true],
        ["3-Yr Earnings Growth", eq.growth3y != null ? eq.growth3y.toFixed(2) + "%" : "—", null, true],
      ];
      equity =
        "<section class='fm-sec fm-sec--wide'><h3>Equity Valuation</h3>" +
        "<table class='fm-ratios'><thead><tr><th>Metric</th><th class='num'>Fund</th>" +
        (showCat ? "<th class='num'>Category avg</th>" : "") + "</tr></thead><tbody>" +
        rowsE.map((r) => {
          const fund = r[3] ? r[1] : (r[1] != null ? r[1].toFixed(2) : "—");
          const c = r[3] ? "" : (r[2] != null ? r[2].toFixed(2) : "—");
          return "<tr><td>" + r[0] + "</td><td class='num'>" + fund + "</td>" +
            (showCat ? "<td class='num'>" + c + "</td>" : "") + "</tr>";
        }).join("") + "</tbody></table></section>";
    }

    const catFamily = [d.category, d.family].filter(Boolean).join(" · ");
    els.modalBody.innerHTML =
      "<div class='fm-head'>" +
        "<div class='fm-head__id'>" +
          "<h2 id='fm-name' class='fm-name'>" + d.name +
            " <span class='fm-ticker'>" + d.ticker + "</span></h2>" +
          (catFamily ? "<div class='fm-catfam'>" + typeChip(d.type) + catFamily + "</div>" : "") +
        "</div>" +
        "<div class='fm-price'>" +
          "<div class='fm-price__val'>" + fmtMoney(d.price, d.currency) + "</div>" + chg +
          (d.as_of ? "<div class='fm-asof'>as of " +
            new Date(d.as_of).toLocaleDateString(undefined, { month: "short", day: "numeric", year: "numeric" }) +
            "</div>" : "") +
        "</div>" +
      "</div>" +
      "<div class='fm-stats'>" + facts + "</div>" +
      grid1 + grid2 + equity +
      "<p class='fm-note'>Composition, holdings, and valuation data from Yahoo Finance and may be " +
      "delayed. Holdings shown are the top 10 only. P/E, P/B, P/S and P/CF are portfolio aggregates. " +
      "Educational use only — not investment advice.</p>";
  }

  function closeModal() {
    els.modal.classList.add("hidden");
    els.modalBody.innerHTML = "";
    document.body.classList.remove("modal-open");
  }

  // ---- error --------------------------------------------------------------
  function showError(msg) {
    if (!msg) { els.error.classList.add("hidden"); return; }
    els.error.textContent = msg;
    els.error.classList.remove("hidden");
  }

  // ---- wiring -------------------------------------------------------------
  function wire() {
    els.tabs.forEach((t) => t.addEventListener("click", () => activateTab(t.dataset.tab)));

    els.select.addEventListener("change", () => selectClass(els.select.value));

    els.showSelect.addEventListener("change", () => {
      const v = els.showSelect.value;
      showCount = v === "all" ? Infinity : parseInt(v, 10);
      if (currentClass) render();
    });

    els.typePills.forEach((p) => p.addEventListener("click", () => {
      els.typePills.forEach((x) => x.classList.remove("active"));
      p.classList.add("active");
      typeFilter = p.dataset.type;
      if (currentClass) render();
    }));

    els.headers.forEach((th) => th.addEventListener("click", () => {
      const key = th.dataset.sort;
      if (sortKey === key) {
        sortDir = sortDir === "asc" ? "desc" : "asc";
      } else {
        sortKey = key;
        sortDir = LOWER_IS_BETTER.has(key) || TEXT_COLS.has(key) ? "asc" : "desc";
      }
      if (currentClass) render();
    }));

    // Row checkboxes (delegated — the tbody is rebuilt on every render).
    els.tbody.addEventListener("change", (e) => {
      const cb = e.target.closest(".fund-check");
      if (!cb) return;
      const ticker = cb.dataset.ticker;
      if (cb.checked) {
        if (selected.size >= MAX_SELECT) { cb.checked = false; return; }
        selected.add(ticker);
      } else {
        selected.delete(ticker);
      }
      selectionChanged();
    });

    // Selection bar: remove a chip, clear all, or send to Compare.
    els.selection.addEventListener("click", (e) => {
      const rm = e.target.closest("[data-remove]");
      if (rm) { selected.delete(rm.dataset.remove); selectionChanged(); return; }
      if (e.target.closest("#clear-selection")) { clearSelection(); return; }
      if (e.target.closest("#compare-selected")) { compareSelected(); return; }
    });

    // Fund name -> open the detail modal.
    els.tbody.addEventListener("click", (e) => {
      const link = e.target.closest(".fund-link");
      if (link) openFundDetail(link.dataset.ticker);
    });

    // Modal close: × button, backdrop, or Escape.
    els.modal.addEventListener("click", (e) => {
      if (e.target.closest("[data-fm-close]")) closeModal();
    });
    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape" && !els.modal.classList.contains("hidden")) closeModal();
    });
  }

  // Exposed so the Compare tab (main.js) can open the same modal.
  window.FundDetail = { open: openFundDetail };

  document.addEventListener("DOMContentLoaded", wire);
})();
